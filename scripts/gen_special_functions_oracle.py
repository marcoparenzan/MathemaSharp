"""Generates src/tests/MathemaSharp.Core.Tests/SpecialFunctionsOracle.g.cs: reference values of erf, erfc, gamma and lgamma computed by
CPython's math module (C99 libm), for the tests of MathemaSharp.Core.SpecialFunctions (erf, erfc, gamma, lgamma, expm1, log1p). Run with the system Python (no packages needed):

    python -I scripts/gen_special_functions_oracle.py

The points are fixed (no random numbers), so the output is reproducible. Values are written with repr(), which round-trips a double.
"""
import math
import os
import sys

xs_erf = sorted({round(0.05 * i, 10) for i in range(-120, 121)} | {1e-300, 1e-20, 1e-8, 0.4375, 1.0, 2.0, 2.5, 3.0, 4.0, 5.5, 8.0, 10.0, 20.0, 26.0, 26.5})
xs_gamma = sorted({round(0.0625 * i, 10) for i in range(-480, 2740) if 0.0625 * i != int(0.0625 * i) or 0.0625 * i > 0}
                  | {1e-19, 1e-10, 0.5, 1.5, 2.5, 22.0, 23.0, 24.0, 25.0, 100.5, 139.5, 140.5, 170.5, 171.5, 171.62, -0.5, -1.5, -2.5, -10.25, -30.75, -100.5, -150.5})
xs_gamma = [x for x in xs_gamma if not (x <= 0 and x == math.floor(x))]

def num(v):
    if math.isinf(v):
        return 'double.PositiveInfinity' if v > 0 else 'double.NegativeInfinity'
    return repr(v)

lines = []
lines.append('// <auto-generated> by scripts/gen_special_functions_oracle.py from CPython %s math; do not edit. </auto-generated>' % sys.version.split()[0])
lines.append('namespace MathemaSharp.Core.Tests;')
lines.append('')
lines.append('internal static class SpecialFunctionsOracle')
lines.append('{')
lines.append('    /// <summary>x, erf(x), erfc(x).</summary>')
lines.append('    public static readonly (double X, double Erf, double Erfc)[] ErfPoints =')
lines.append('    {')
for x in xs_erf:
    lines.append('        (%s, %s, %s),' % (num(x), num(math.erf(x)), num(math.erfc(x))))
lines.append('    };')
lines.append('')
lines.append('    /// <summary>x, gamma(x) (+∞ where CPython raises OverflowError), lgamma(x).</summary>')
lines.append('    public static readonly (double X, double Gamma, double LogAbsGamma)[] GammaPoints =')
lines.append('    {')
for x in xs_gamma:
    try:
        g = math.gamma(x)
    except OverflowError:
        g = math.inf
    lines.append('        (%s, %s, %s),' % (num(x), num(g), num(math.lgamma(x))))
lines.append('    };')
lines.append('}')

xs_small = sorted({0.0, 1e-300, 1e-100, 1e-20, 1e-16, 1e-10, 1e-8, 1e-5, 1e-3, 0.1, 0.5, 1.0, 5.0, 20.0, 100.0, 700.0, -1e-300, -1e-20, -1e-10, -1e-5, -0.1, -0.5, -1.0, -5.0, -20.0, -40.0, -800.0})
xs_log = sorted({0.0, 1e-300, 1e-100, 1e-20, 1e-16, 1e-10, 1e-8, 1e-5, 1e-3, 0.1, 0.5, 1.0, 5.0, 1e5, 1e10, 1e100, 1e300, -1e-300, -1e-20, -1e-10, -1e-5, -0.1, -0.5, -0.9, -0.999, -0.999999999, -1 + 2.0 ** -52})
lines[-1:-1] = [
    '',
    '    /// <summary>x, expm1(x) (+inf where CPython raises OverflowError).</summary>',
    '    public static readonly (double X, double ExpM1)[] ExpM1Points =',
    '    {',
]
for x in xs_small:
    try:
        v = math.expm1(x)
    except OverflowError:
        v = math.inf
    lines.insert(-1, '        (%s, %s),' % (num(x), num(v)))
lines.insert(-1, '    };')
lines[-1:-1] = [
    '',
    '    /// <summary>x, log1p(x).</summary>',
    '    public static readonly (double X, double LogP1)[] LogP1Points =',
    '    {',
]
for x in xs_log:
    lines.insert(-1, '        (%s, %s),' % (num(x), num(math.log1p(x))))
lines.insert(-1, '    };')

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'tests', 'MathemaSharp.Core.Tests', 'SpecialFunctionsOracle.g.cs')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('erf points', len(xs_erf), 'gamma points', len(xs_gamma), 'expm1 points', len(xs_small), 'log1p points', len(xs_log))
