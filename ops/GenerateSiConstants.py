"""Generate only seven SI defining records from verified raw NIST data."""
import hashlib
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]
hash_value = '77fb90e66c40db3e6eb16630bc9c88e4c7c8beddbe5e71be406f2f26e3f67e67'
snapshot = pathlib.Path(r'D:\Dev\BuildArtifacts\sources\nist-codata') / (hash_value + '.txt')
raw = snapshot.read_bytes()
if hashlib.sha256(raw).hexdigest() != hash_value:
    raise RuntimeError('Raw NIST checksum mismatch')
text = raw.decode('utf-8')
if '2022 CODATA adjustment' not in text:
    raise RuntimeError('Wrong edition')
source = {}
started = False
for line in text.splitlines():
    if not started:
        started = len(line) >= 100 and set(line) == {'-'}
        continue
    if line.strip():
        source[line[:60].strip()] = (line[60:85].strip(), line[85:110].strip(), line[110:].strip())
data = json.loads((root / 'ops/data/codata2022.json').read_text(encoding='utf-8-sig'))
if data['sha256'] != hash_value or data['edition'] != 2022:
    raise RuntimeError('Structured source provenance mismatch')
rows = {row['name']: row for row in data['records']}
selected = [('speed of light in vacuum', 'c'), ('Planck constant', 'h'),
            ('Boltzmann constant', 'k'), ('elementary charge', 'e'),
            ('Avogadro constant', 'N_A'), ('hyperfine transition frequency of Cs-133', 'Δν_Cs'),
            ('luminous efficacy', 'K_cd')]
header = '// Copyright (c) 2026 Marco Parenzan\n// Licensed under the MIT License. See the LICENSE file in the project root.\n// <auto-generated>ops/GenerateSiConstants.py; NIST CODATA2022; raw SHA256 ' + hash_value + '.</auto-generated>\nnamespace MathemaSharp;\n\npublic static partial class PhysicalConstants\n{\n    private static PhysicalConstantDefinition[] CreateDefinitions() =>\n    [\n'
for name, symbol in selected:
    row = rows[name]
    printed, uncertainty, unit = source[name]
    if uncertainty != '(exact)' or '...' in printed or not row['isExact'] or row['valueIsTruncated']:
        raise RuntimeError('Not an untruncated exact defining record: ' + name)
    value = printed.replace(' ', '')
    if row['decimalValue'] != value or row['unit'] != unit or row['decimalUncertainty'] != '0':
        raise RuntimeError('Structured/raw source mismatch: ' + name)
    header += f'        new("{name}", "{symbol}", "{value}", "{unit}", "{hash_value}"),\n'
header += '    ];\n}\n'
(root / 'src/libs/MathemaSharp.Core/PhysicalConstants.g.cs').write_text(header, encoding='utf-8', newline='\n')
print('Generated seven exact SI definitions; raw and structured NIST data agree.')
