"""Generate mathematical constants; never hand-edit generated C# or reference data."""
import decimal
import json
import os
import pathlib
import sys

sys.path.insert(0, os.environ.get('SCIENCE_MPMATH_PATH', r'D:\Dev\BuildArtifacts\tools\mpmath-1.3.0'))
import mpmath as mp
if mp.__version__ != '1.3.0':
    raise RuntimeError('Expected pinned mpmath 1.3.0')


def value(name):
    return {'Pi': lambda: mp.pi, 'Tau': lambda: 2 * mp.pi, 'E': lambda: mp.e,
            'Sqrt2': lambda: mp.sqrt(2), 'Ln2': lambda: mp.log(2),
            'Ln10': lambda: mp.log(10), 'Sqrt3': lambda: mp.sqrt(3),
            'Log2E': lambda: 1 / mp.log(2), 'Log10E': lambda: 1 / mp.log(10),
            'EulerGamma': lambda: mp.euler, 'GoldenRatio': lambda: (1 + mp.sqrt(5)) / 2,
            'Catalan': lambda: mp.catalan, 'Apery': lambda: mp.zeta(3)}[name]()


def binary_bits(number, precision, exponent_bits):
    # Positive normal constants only: exact integer significand rounding, ties-even.
    exponent = int(mp.floor(mp.log(number, 2)))
    scaled = number * mp.power(2, precision - 1 - exponent)
    lower = int(mp.floor(scaled))
    fraction = scaled - lower
    significand = lower + int(fraction > mp.mpf('0.5') or (fraction == mp.mpf('0.5') and lower % 2 == 1))
    if significand == 1 << precision:
        significand >>= 1
        exponent += 1
    bias = (1 << (exponent_bits - 1)) - 1
    encoded = ((exponent + bias) << (precision - 1)) | (significand - (1 << (precision - 1)))
    width = (1 + exponent_bits + precision - 1) // 4
    return f'{encoded:0{width}x}'


root = pathlib.Path(__file__).resolve().parents[1]
records = []
for name in ['Pi', 'Tau', 'E', 'Sqrt2', 'Ln2', 'Ln10', 'Sqrt3', 'Log2E', 'Log10E',
             'EulerGamma', 'GoldenRatio', 'Catalan', 'Apery']:
    with mp.workdps(160):
        first = mp.nstr(value(name), 100)
    with mp.workdps(200):
        number = value(name)
        text = mp.nstr(number, 100)
        if first != text:
            raise RuntimeError('Unstable constant: ' + name)
        bits = {'Half': binary_bits(number, 11, 5), 'Single': binary_bits(number, 24, 8),
                'Double': binary_bits(number, 53, 11)}
    rounded = {}
    with decimal.localcontext() as context:
        context.prec = 110
        context.rounding = decimal.ROUND_HALF_EVEN
        for typename, precision in [('Decimal32', 7), ('Decimal64', 16), ('Decimal128', 34)]:
            reference = decimal.Decimal(text)
            exponent = reference.adjusted() + 1 - precision
            rounded[typename] = str(reference.quantize(decimal.Decimal(1).scaleb(exponent)))
    records.append({'id': name, 'status': 'Mathematical', 'source': 'mpmath 1.3.0',
                    'significantDigits': 100, 'value': text, 'binaryBits': bits, 'decimalValues': rounded})
header = '// Copyright (c) 2026 Marco Parenzan\n// Licensed under the MIT License. See the LICENSE file in the project root.\n// <auto-generated>ops/GenerateMathConstants.py; mpmath 1.3.0; 160/200 dps; 100 stable digits.</auto-generated>\nnamespace MathemaSharp;\n\ninternal static class MathematicalConstantData\n{\n'
source = header + ''.join(f'    internal const string {record["id"]} = "{record["value"]}";\n' for record in records) + '}\n'
(root / 'src/libs/MathemaSharp.Core/MathematicalConstantData.g.cs').write_text(source, encoding='utf-8', newline='\n')
